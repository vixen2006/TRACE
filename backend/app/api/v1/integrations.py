"""
GitHub OAuth integration endpoints.
Every token is encrypted at rest before storage.
OAuth state is validated to prevent CSRF attacks.
"""
import secrets
from typing import Annotated
from urllib.parse import urlencode

import httpx
from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import settings
from app.core.database import get_db
from app.core.deps import CurrentUser
from app.core.security import decrypt_token, encrypt_token
from app.models.models import Connection, User
from app.schemas.schemas import ConnectionOut

from app.api.v1.auth import _oauth_states as auth_oauth_states
from app.api.v1.auth import github_callback as auth_github_callback

router = APIRouter()

# In-memory state store — use Redis in production
_oauth_states: dict[str, str] = {}  # state -> user_id


@router.get("/github/connect")
async def github_connect(current_user: CurrentUser) -> dict:
    """
    Generate the GitHub OAuth authorization URL.
    Returns the URL for the frontend to redirect to.
    State token prevents CSRF.
    """
    state = secrets.token_urlsafe(32)
    _oauth_states[state] = str(current_user.id)

    params = {
        "client_id": settings.github_client_id,
        "redirect_uri": settings.github_redirect_uri,
        "scope": "repo,read:user",
        "state": state,
    }
    auth_url = "https://github.com/login/oauth/authorize?" + urlencode(params)
    return {"auth_url": auth_url, "state": state}


@router.get("/github/callback")
async def github_callback(
    code: str,
    state: str,
    db: Annotated[AsyncSession, Depends(get_db)],
):
    """
    Handle GitHub OAuth callback.
    If state belongs to login flow, executes auth_github_callback (creates user, sets session, redirects to dashboard).
    Otherwise, handles repo connection for existing authenticated user.
    """
    # Check if this state was generated by the login flow
    if state in auth_oauth_states:
        return await auth_github_callback(code=code, state=state, db=db)

    # Validate state for connected user integration flow
    user_id = _oauth_states.pop(state, None)
    if not user_id:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid or expired OAuth state.")

    # Exchange code for access token
    async with httpx.AsyncClient(timeout=15) as client:
        token_resp = await client.post(
            "https://github.com/login/oauth/access_token",
            json={
                "client_id": settings.github_client_id,
                "client_secret": settings.github_client_secret,
                "code": code,
                "redirect_uri": settings.github_redirect_uri,
            },
            headers={"Accept": "application/json"},
        )
        token_data = token_resp.json()

    if "error" in token_data:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"GitHub OAuth error: {token_data.get('error_description', token_data['error'])}",
        )

    raw_token = token_data["access_token"]
    scopes = token_data.get("scope", "")

    # Identify the GitHub user
    async with httpx.AsyncClient(timeout=15) as client:
        user_resp = await client.get(
            "https://api.github.com/user",
            headers={
                "Authorization": f"Bearer {raw_token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
            },
        )
        github_user = user_resp.json()

    github_user_id = str(github_user["id"])
    github_username = github_user["login"]

    # Upsert the connection (one per user per provider)
    existing = await db.execute(
        select(Connection).where(
            Connection.user_id == user_id,
            Connection.provider == "github",
        )
    )
    conn = existing.scalar_one_or_none()

    encrypted = encrypt_token(raw_token)

    if conn:
        conn.encrypted_token = encrypted
        conn.external_user_id = github_user_id
        conn.external_username = github_username
        conn.scopes = scopes
        conn.sync_status = "idle"
    else:
        conn = Connection(
            user_id=user_id,
            provider="github",
            external_user_id=github_user_id,
            external_username=github_username,
            encrypted_token=encrypted,
            scopes=scopes,
            sync_status="idle",
        )
        db.add(conn)

    await db.flush()
    return {
        "status": "connected",
        "github_username": github_username,
        "connection_id": str(conn.id),
    }


@router.get("", response_model=list[ConnectionOut])
async def list_integrations(
    current_user: CurrentUser,
    db: Annotated[AsyncSession, Depends(get_db)],
) -> list[Connection]:
    """List all OAuth connections for the current user."""
    result = await db.execute(
        select(Connection).where(Connection.user_id == current_user.id)
    )
    return list(result.scalars().all())


@router.delete("/{connection_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_integration(
    connection_id: str,
    current_user: CurrentUser,
    db: Annotated[AsyncSession, Depends(get_db)],
) -> None:
    """
    Disconnect an integration. Validates ownership before deletion.
    The encrypted token is deleted; raw token is never retrieved.
    """
    result = await db.execute(
        select(Connection).where(
            Connection.id == connection_id,
            Connection.user_id == current_user.id,  # enforce ownership
        )
    )
    conn = result.scalar_one_or_none()
    if not conn:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Connection not found.")
    await db.delete(conn)
